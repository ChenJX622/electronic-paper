#ifndef __MPU6050_H
#define __MPU6050_H

#include "hal_data.h"
#include <stdint.h>

/***********************************************************************************************************************
 * MPU6050 寄存器定义
 **********************************************************************************************************************/
#define MPU6050_ADDR        0x68
#define MPU6050_PWR_MGMT_1  0x6B
#define MPU6050_SMPLRT_DIV  0x19
#define MPU6050_GYRO_CONFIG 0x1B
#define MPU6050_ACC_CONFIG  0x1C
#define MPU6050_DATA_START  0x3B
#define MPU6050_WHO_AM_I    0x75

/***********************************************************************************************************************
 * MPU6050 数据结构体
 **********************************************************************************************************************/
typedef struct {
    int16_t acc_x;
    int16_t acc_y;
    int16_t acc_z;
    int16_t gyro_x;
    int16_t gyro_y;
    int16_t gyro_z;
    float   temp_c;
} mpu6050_data_t;

/***********************************************************************************************************************
 * 函数声明
 **********************************************************************************************************************/
/**
 * @brief 初始化 MPU6050
 * @retval FSP_SUCCESS 初始化成功
 * @retval 其他 初始化失败
 */
fsp_err_t mpu6050_init(void);

/**
 * @brief 读取 MPU6050 完整传感器数据
 * @param[out] data 输出参数，存储读取到的加速度、陀螺仪和温度数据
 * @retval FSP_SUCCESS 读取成功
 * @retval 其他 读取失败
 */
fsp_err_t mpu6050_read(mpu6050_data_t *data);

#endif // __MPU6050_H